#!/usr/bin/env python3
"""Write build/web/sw.js: an offline app-shell cache for the PWA.

Every built file is precached under a cache named by the hash of the
build, so a new deploy installs a fresh cache and drops the old one. API
calls go to a different origin and are never cached."""
import hashlib
import json
import os
import sys

root = sys.argv[1]
files = []
h = hashlib.sha256()
for dirpath, _, names in os.walk(root):
    for n in sorted(names):
        full = os.path.join(dirpath, n)
        rel = os.path.relpath(full, root).replace(os.sep, "/")
        if rel in ("sw.js", "flutter_service_worker.js") or rel.endswith(".map") or rel.startswith("."):
            continue
        files.append(rel)
        with open(full, "rb") as f:
            h.update(rel.encode() + b"\0" + f.read())
files.sort()
version = h.hexdigest()[:16]
precache = ["./"] + files

sw = f"""// Generated by tool/write_sw.py. Do not edit.
const CACHE = 'clavium-{version}';
const PRECACHE = {json.dumps(precache)};

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', (e) => {{
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('clavium-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
}});

self.addEventListener('fetch', (e) => {{
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;
  e.respondWith(
    caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => {{
      if (hit) return hit;
      return fetch(e.request).catch(() =>
        e.request.mode === 'navigate' ? caches.match('./') : Response.error());
    }}),
  );
}});
"""
with open(os.path.join(root, "sw.js"), "w") as f:
    f.write(sw)
print(f"sw.js: {len(precache)} files, cache clavium-{version}")
